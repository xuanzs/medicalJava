    private void btnAddActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAddActionPerformed
        // TODO add your handling code here:
        String id = String.format(txtId.getText()).trim();
        String name = String.format(txtName.getText()).trim();
        String desc = String.format(txtDesc.getText()).trim();
        
        if(id.isEmpty() || name.isEmpty() || desc.isEmpty()){
            JOptionPane.showMessageDialog(null, "Please fill in all field", "Empty Values", JOptionPane.WARNING_MESSAGE);
            return;
        }else if(ifIdExist(id)){
            JOptionPane.showMessageDialog(null, "Assessment type ID is duplicated", "Duplicated Department ID", JOptionPane.WARNING_MESSAGE);
            return;
        }else{
            try{
                FileWriter fw = new FileWriter("data/assessmentType.txt", true);
                BufferedWriter bw = new BufferedWriter(fw);

                bw.write(String.format("%s, %s, %s", id, name, desc));
                bw.newLine();

                bw.close();
                fw.close();
            }catch(IOException e){
                JOptionPane.showMessageDialog(null, e, "Error", JOptionPane.ERROR_MESSAGE);
            }catch(Exception e){
                JOptionPane.showMessageDialog(null, e, "Error", JOptionPane.ERROR_MESSAGE);
            }
            JOptionPane.showMessageDialog(null, String.format("New assessment type: %s is added successfully", name), "Success", JOptionPane.INFORMATION_MESSAGE);
            loadTable();
            txtId.setText("");
            txtName.setText("");
            txtDesc.setText("");
            
            txtId.setEditable(true);
            txtId.requestFocusInWindow();
        }
    }//GEN-LAST:event_btnAddActionPerformed

    private void btnUpdateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUpdateActionPerformed
        // TODO add your handling code here:
        String id = String.format(txtId.getText()).trim();
        String newName = String.format(txtName.getText()).trim();
        String newDesc = String.format(txtDesc.getText()).trim();
        
        row = assessmentTable.getSelectedRow();
        
        if(row == -1){
            JOptionPane.showMessageDialog(null, "Please select a row to edit", "Empty Values", JOptionPane.WARNING_MESSAGE);
            return;
        }else if(id.isEmpty() || newName.isEmpty() || newDesc.isEmpty()){
            JOptionPane.showMessageDialog(null, "Please fill in all field", "Empty Values", JOptionPane.WARNING_MESSAGE);
            return;
        }else{
            try{
                FileReader fr = new FileReader("data/assessmentType.txt");
                BufferedReader br = new BufferedReader(fr);

                String line = null;
                List<String> lines = new ArrayList<>();

                while((line = br.readLine()) != null){
                    String[] items = line.split(", ");
                    if (items[0].equals(id)){
                        line = String.format("%s, %s, %s", id, newName, newDesc);
                    }
                    lines.add(line);
                }

                br.close();
                fr.close();

                // Write information back to assessmentType.txt file
                FileWriter fw = new FileWriter("data/assessmentType.txt");
                BufferedWriter bw = new BufferedWriter(fw);

                for(String item : lines){
                    bw.write(item);
                    bw.newLine();
                }

                bw.close();
                fw.close();
            }catch(IOException e){
                JOptionPane.showMessageDialog(null, e, "Error", JOptionPane.ERROR_MESSAGE);
            }catch(Exception e){
                JOptionPane.showMessageDialog(null, e, "Error", JOptionPane.ERROR_MESSAGE);
            }
            JOptionPane.showMessageDialog(null, String.format("%s has been updated successfully", newName), "Success", JOptionPane.INFORMATION_MESSAGE);
            loadTable();
            txtId.setText("");
            txtName.setText("");
            txtDesc.setText("");
            
            txtId.setEditable(true);
            txtId.requestFocusInWindow();
            
            assessmentTable.clearSelection();
        }
    }//GEN-LAST:event_btnUpdateActionPerformed

    private void btnRemoveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRemoveActionPerformed
        // TODO add your handling code here:
        String id = String.format(txtId.getText()).trim();
        
        row = assessmentTable.getSelectedRow();
        
        if(row == -1){
            JOptionPane.showMessageDialog(null, "Please select a row to delete", "Empty Values", JOptionPane.WARNING_MESSAGE);
            return;
        }else{
            // get deleted department name
            String name = assessmentTable.getValueAt(row, 1).toString().trim();
            
            int confirm = JOptionPane.showConfirmDialog(null, String.format("Are you sure you want to delete %s? ", name), "Confirm Delete", JOptionPane.YES_NO_OPTION);

            if (confirm == JOptionPane.NO_OPTION) {
                return; 
            }
            try{
            FileReader fr = new FileReader("data/assessmentType.txt");
            BufferedReader br = new BufferedReader(fr);
            
            String line = null;
            List<String> lines = new ArrayList<>();
            
            while((line = br.readLine()) != null){
                String[] items = line.split(", ");
                if (!items[0].equals(id)){
                    lines.add(line);
                }
            }
            
            br.close();
            fr.close();
            
            // Write information back to assessmentType.txt file
            FileWriter fw = new FileWriter("data/assessmentType.txt");
            BufferedWriter bw = new BufferedWriter(fw);
            
            for(String item : lines){
                bw.write(item);
                bw.newLine();
            }
            
            bw.close();
            fw.close();
            
            JOptionPane.showMessageDialog(null, String.format("%s has been removed successfully", name), "Success", JOptionPane.INFORMATION_MESSAGE);
            loadTable();
            txtId.setText("");
            txtName.setText("");
            txtDesc.setText("");
            
            txtId.setEditable(true);
            }catch(IOException e){
                JOptionPane.showMessageDialog(null, e, "Error", JOptionPane.ERROR_MESSAGE);
            }catch(Exception e){
                JOptionPane.showMessageDialog(null, e, "Error", JOptionPane.ERROR_MESSAGE);
            }
        }
        assessmentTable.clearSelection();
        txtId.requestFocusInWindow();
    }//GEN-LAST:event_btnRemoveActionPerformed

