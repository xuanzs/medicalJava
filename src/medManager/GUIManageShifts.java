    public void loadTable(){
        model.setRowCount(0);
        
        // filter past shifts
        List<String[]> tempShift = new ArrayList<>();
        try{
            FileReader fr = new FileReader("data/shiftRoster.txt");
            BufferedReader br = new BufferedReader(fr);
            
            String line = null;
            
            while((line = br.readLine()) != null){
                String[] items = line.split(", ");
                
                // check on past shifts
                try{
                    LocalDate today = LocalDate.now();
                    LocalTime now = LocalTime.now();
                    LocalDate date = LocalDate.parse(items[1]);
                    LocalTime time = LocalTime.parse(items[2]);

                    if(date.isBefore(today)){
                        continue;
                    }else if(date.isEqual(today) && time.isBefore(now)){
                        continue;
                    }
                    tempShift.add(items);
                }catch(DateTimeParseException e){
                    JOptionPane.showMessageDialog(null, e, "Invalid Date Time", JOptionPane.ERROR_MESSAGE);
                }
            }
            
            fr.close();
            br.close();
        }catch(IOException e){
            JOptionPane.showMessageDialog(null, e, "Error", JOptionPane.ERROR_MESSAGE);
        }
        
        // sort the list
        tempShift.sort(Comparator.comparing((String[] items) -> items[1]).thenComparing(items -> items[2]).thenComparing(items -> items[3]));
        
        // rewrite the filtered list
        try{
            FileWriter fw = new FileWriter("data/shiftRoster.txt");
            BufferedWriter bw = new BufferedWriter(fw);
            
            for(String[] line: tempShift){
                bw.write(String.join(", ", line));
                bw.newLine();
                model.addRow(line);
            }
            
            bw.close();
            fw.close();
        }catch(IOException e){
            JOptionPane.showMessageDialog(null, e, "Error", JOptionPane.ERROR_MESSAGE);
        }
        
        // store all doctor information to a list
        List<String> tempDoc = new ArrayList<>();
        try{
            FileReader fr = new FileReader(docFile);
            BufferedReader br = new BufferedReader(fr);

            String line = null;

            while((line = br.readLine()) != null){
                tempDoc.add(line);
            }

            fr.close();
            br.close();
        }catch(IOException e){
            JOptionPane.showMessageDialog(null, e, "Error", JOptionPane.ERROR_MESSAGE);
        }

        // insert information for the last column: Doctor Name
        for(int row = 0; row < shiftTable.getRowCount(); row++){
            String checkDocId = shiftTable.getValueAt(row, 4).toString().trim();
            String docName = null;
            
            for(String line : tempDoc){
                String[] items = line.split(", ");
                String docId = items[idIndex];
                if(docId.equals(checkDocId)){
                    docName = items[nameIndex];
                    break;
                }
            }
            
            shiftTable.setValueAt(docName, row, 5);
        }
    }
    
