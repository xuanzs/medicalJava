    private void btnAddActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAddActionPerformed
        // TODO add your handling code here:
        try{
            String shiftId = txtShiftId.getText();
            String strDate = txtDate.getText();
            String strStartTime = txtStartTime.getText();
            String strEndTime = txtEndTime.getText();
            String docId = txtDocId.getText();


            LocalDate today = LocalDate.now();
            LocalTime now = LocalTime.now();

            if(shiftId.contains(" ") || strDate.contains(" ") || strStartTime.contains(" ") || strEndTime.contains(" ")){
                JOptionPane.showMessageDialog(null, "Please fill in all field", "Empty Values", JOptionPane.WARNING_MESSAGE);
                return;
            }

            if(cmbDocName.getSelectedIndex() == -1){
                JOptionPane.showMessageDialog(null, "Please choose a doctor on duty", "Empty Values", JOptionPane.WARNING_MESSAGE);
                return;
            }
            String docName = cmbDocName.getSelectedItem().toString();


            if(ifIdExist(shiftId)){
                JOptionPane.showMessageDialog(null, "Shift ID is duplicated", "Duplicated Shift ID", JOptionPane.WARNING_MESSAGE);
                return;
            }
            // parse date and time to LocalDate and LocalTime
            LocalDate date = LocalDate.parse(strDate);
            LocalTime startTime = LocalTime.parse(strStartTime);
            LocalTime endTime = LocalTime.parse(strEndTime);

            if(date.isBefore(today)){
                JOptionPane.showMessageDialog(null, "Please enter a valid date", "Invalid Input", JOptionPane.ERROR_MESSAGE);
                return;
            }else if(date.isEqual(today)){
                if(startTime.isBefore(now) || endTime.isBefore(now)){
                    JOptionPane.showMessageDialog(null, "Please enter a valid time", "Invalid Input", JOptionPane.ERROR_MESSAGE);
                    return;
                }
            }

            if(endTime.isBefore(startTime) || endTime.equals(startTime)){
                JOptionPane.showMessageDialog(null, "Please enter a valid end time", "Invalid Input", JOptionPane.ERROR_MESSAGE);
                return;
            }
            
            Duration duration = Duration.between(startTime, endTime);
            if(duration.toMinutes() < 480 || duration.toMinutes() > 1440){
                JOptionPane.showMessageDialog(null, "Shift duration should in between 8 to 24 hours", "Shift Duration Out of Range", JOptionPane.WARNING_MESSAGE);
                return;
            }
            
            // save the new shift to shiftRoster.txt
            manager.designShift(shiftId, date, startTime, endTime, docId);
            JOptionPane.showMessageDialog(null, String.format("New shift successfully assigned to Doctor %s", docName), "Success", JOptionPane.INFORMATION_MESSAGE);
            
            // interface reload
            loadTable();
            txtShiftId.setText(null);
            txtDate.setValue(null);
            txtStartTime.setValue(null);
            txtEndTime.setValue(null);
            cmbDocName.setSelectedIndex(-1);
            txtShiftId.requestFocusInWindow();
        }catch(DateTimeParseException e){
            JOptionPane.showMessageDialog(null, "Please enter a valid date and time in the correct format", "Invalid Input", JOptionPane.ERROR_MESSAGE);
        }catch(Exception e){
            JOptionPane.showMessageDialog(null, e, "Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnAddActionPerformed

