    private void btnDelActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDelActionPerformed
        // TODO add your handling code here:
        String id = String.format(txtShiftId.getText());
        
        row = shiftTable.getSelectedRow();
        
        if(row == -1){
            JOptionPane.showMessageDialog(null, "Please select a row to delete", "Empty Values", JOptionPane.WARNING_MESSAGE);
            return;
        }else{
            int confirm = JOptionPane.showConfirmDialog(null, "Are you sure you want to delete the selected shift? ", "Confirm Delete", JOptionPane.YES_NO_OPTION);

            if (confirm == JOptionPane.NO_OPTION) {
                return; 
            }
            try{
            FileReader fr = new FileReader("data/shiftRoster.txt");
            BufferedReader br = new BufferedReader(fr);
            
            String line = null;
            List<String> lines = new ArrayList<>();
            
            while((line = br.readLine()) != null){
                String[] items = line.split(", ");
                if (!items[0].equals(id)){
                    lines.add(line);
                }
            }
            
            br.close();
            fr.close();
            
            // Write information back to shiftRoster.txt file
            FileWriter fw = new FileWriter("data/shiftRoster.txt");
            BufferedWriter bw = new BufferedWriter(fw);
            
            for(String item : lines){
                bw.write(item);
                bw.newLine();
            }
            
            bw.close();
            fw.close();
            
            JOptionPane.showMessageDialog(null, String.format("Selected shift has been removed successfully"), "Success", JOptionPane.INFORMATION_MESSAGE);
            loadTable();
            txtShiftId.setText(null);
            txtDate.setValue(null);
            txtStartTime.setValue(null);
            txtEndTime.setValue(null);
            cmbDocName.setSelectedIndex(-1);
            txtShiftId.setEditable(true);
            shiftTable.clearSelection();
            txtShiftId.requestFocusInWindow();
            }catch(IOException e){
                JOptionPane.showMessageDialog(null, e, "Error", JOptionPane.ERROR_MESSAGE);
            }catch(Exception e){
                JOptionPane.showMessageDialog(null, e, "Error", JOptionPane.ERROR_MESSAGE);
            }
        }
    }//GEN-LAST:event_btnDelActionPerformed

