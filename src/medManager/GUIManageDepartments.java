    public void loadTable(){
        model.setRowCount(0);
        
        try{
            FileReader fr = new FileReader("data/departments.txt");
            BufferedReader br = new BufferedReader(fr);
            
            String line = null;
            String[] items;
            
            while((line = br.readLine()) != null){
                items = line.split(", ");
                model.addRow(items);
            }
            
            fr.close();
            br.close();
        }catch(IOException e){
            JOptionPane.showMessageDialog(null, e, "Error", JOptionPane.ERROR_MESSAGE);
        }
    }
    
    public boolean ifIdExist(String checkId){
        for(int row = 0; row < deptTable.getRowCount(); row++){
            String id = deptTable.getValueAt(row, 0).toString().trim();
            if (id.equals(checkId)){
                return true;
            }
        }
        return false;
    }

