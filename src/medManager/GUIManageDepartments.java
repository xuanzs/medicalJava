    private void btnAddActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAddActionPerformed
        // TODO add your handling code here:
        String id = String.format(txtId.getText()).trim();
        String name = String.format(txtName.getText()).trim();
        String desc = String.format(txtDesc.getText()).trim();
        
        if(id.isEmpty() || name.isEmpty() || desc.isEmpty()){
            JOptionPane.showMessageDialog(null, "Please fill in all field", "Empty Values", JOptionPane.WARNING_MESSAGE);
            return;
        }else if(ifIdExist(id)){
            JOptionPane.showMessageDialog(null, "Department ID is duplicated", "Duplicated Department ID", JOptionPane.WARNING_MESSAGE);
            return;
        }else{
            manager.createDepartment(id, name, desc);
            JOptionPane.showMessageDialog(null, String.format("New department: %s is added successfully", name), "Success", JOptionPane.INFORMATION_MESSAGE);
            loadTable();
            txtId.setText("");
            txtName.setText("");
            txtDesc.setText("");
            
            txtId.setEditable(true);
            txtId.requestFocusInWindow();
        }
    }//GEN-LAST:event_btnAddActionPerformed

